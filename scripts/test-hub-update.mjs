import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { prepare, digest, verifyLive } from './hub-update.mjs';
const base=JSON.parse(await readFile(new URL('../data/projects.json',import.meta.url),'utf8'));
const journal={version:1,updates:[]};
const original=structuredClone(base);
const project=structuredClone(base.projects[0]); project.next_step='Verified test change';
const u={version:1,id:'test-project-update-01',editor:'chatgpt',date:'2026-10-23',public_safe:true,sources:[{record:'private source',revision:'r1',readback_verified:true}],projects:[{expected_hash:digest(base.projects[0]),project}]};
const next=prepare(base,journal,u);
assert.deepEqual(base,original,'must not mutate input');
assert.deepEqual(next.snapshot.projects.slice(1),base.projects.slice(1),'preserve unrelated projects');
assert.equal(next.snapshot.projects[0].next_step,'Verified test change');
assert.equal(prepare(next.snapshot,next.journal,u).duplicate,true,'repeat must be a no-op');
assert.throws(()=>prepare(next.snapshot,next.journal,{...u,date:'2026-10-24'}),/different content/);
assert.throws(()=>prepare(base,journal,{...u,sources:[]}),/source receipts/);
assert.throws(()=>prepare(base,journal,{...u,public_safe:false}),/public safety/);
assert.throws(()=>prepare(base,journal,{...u,date:'2026-02-30'}),/Invalid date/);
const stale=structuredClone(base); stale.projects[0].summary='Newer work';
assert.throws(()=>prepare(stale,journal,u),/changed since read/);
const removed=structuredClone(u);removed.projects[0].project.tasks.shift();
assert.throws(()=>prepare(base,journal,removed),/history/);
const reopen=structuredClone(u);const done=reopen.projects[0].project.tasks.find(t=>t.status==='done');done.status='todo';
assert.throws(()=>prepare(base,journal,reopen),/reason/);
reopen.projects[0].reopen_reason='Acceptance failed'; assert.ok(prepare(base,journal,reopen));
const added=structuredClone(u);added.projects[0].project.id='new';added.projects[0].expected_hash=null;
assert.throws(()=>prepare(base,journal,added),/duplicate project name/);
added.projects[0].project.name='New project'; assert.equal(prepare(base,journal,added).snapshot.projects.length,base.projects.length+1);
assert.equal(verifyLive(next,next,u.id).status,'live_verified');
assert.throws(()=>verifyLive(next,{snapshot:base,journal:next.journal},u.id),/differs/);
assert.throws(()=>verifyLive(next,{snapshot:next.snapshot,journal},u.id),/not live/);
assert.ok(!JSON.stringify(next.journal).includes('private source'),'private receipts must not be published');
console.log('Update replay, conflict, history, privacy and live-verification tests passed.');
